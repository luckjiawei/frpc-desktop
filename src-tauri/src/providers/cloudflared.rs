use super::{TunnelContext, TunnelProvider};
use crate::db::cloudflared_repo::CloudflaredRepository;
use crate::db::version_repo::VersionRepository;
use crate::downloader::{VersionManager, PROVIDER_CLOUDFLARED};
use crate::models::CloudflaredSettings;
use crate::process::{LaunchSpec, LogClassifier, LogSignal};
use crate::system::FrpcDetector;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};

/// Without `--config`, cloudflared also loads `~/.cloudflared/config.yml` or
/// `/etc/cloudflared/config.yml`, so a user's own setup (credentials file,
/// ingress rules) would leak into this tunnel. An empty file is reported as an
/// `ERR` line, hence the harmless key.
const ISOLATED_CONFIG: &str = "# Generated by Frpc-Desktop. Keeps cloudflared from loading ~/.cloudflared/config.yml.\nno-autoupdate: true\n";

/// Runs a remotely managed Cloudflare Tunnel (`cloudflared tunnel run`).
/// Public hostnames and ingress rules are configured in the Cloudflare
/// dashboard; locally only the connector token and transport flags are kept.
pub struct CloudflaredProvider;

impl CloudflaredProvider {
    fn resolve_binary(
        ctx: &TunnelContext,
        settings: &CloudflaredSettings,
    ) -> Result<PathBuf, (String, String)> {
        if !settings.custom_cloudflared_path.trim().is_empty() {
            let resolved = FrpcDetector::resolve_path(&settings.custom_cloudflared_path);
            if !resolved.exists() || !FrpcDetector::is_executable_binary(&resolved) {
                return Err((
                    "B1005".to_string(),
                    format!(
                        "指定的 cloudflared 文件不存在或不可执行: {}",
                        resolved.display()
                    ),
                ));
            }
            return Ok(resolved);
        }

        if let Some(release_id) = settings.cloudflared_version {
            let conn = ctx.db.conn();
            let version = match VersionRepository::find_by_github_release_id(&conn, release_id) {
                Ok(Some(v)) if v.provider == PROVIDER_CLOUDFLARED => v,
                _ => {
                    return Err((
                        "B1005".to_string(),
                        "未找到 cloudflared 版本（请在下载页面重新下载）".to_string(),
                    ))
                }
            };
            let bin = version
                .local_path
                .as_deref()
                .and_then(VersionManager::resolve_cloudflared_binary);
            return match bin {
                Some(bin) => Ok(bin),
                None => {
                    let _ = VersionRepository::delete_by_github_release_id(&conn, release_id);
                    Err((
                        "B1005".to_string(),
                        "未找到 cloudflared 可执行文件（可能已被删除，已清理无效记录，请重新下载）"
                            .to_string(),
                    ))
                }
            };
        }

        let detected = FrpcDetector::detect_cloudflared();
        if detected.found {
            Ok(PathBuf::from(detected.path))
        } else {
            Err((
                "B1005".to_string(),
                "未配置 cloudflared 路径或下载版本".to_string(),
            ))
        }
    }

    /// Flags placed before `run` apply to the `tunnel` command; the token is
    /// passed through `TUNNEL_TOKEN` so it never shows up in process lists.
    fn build_args(settings: &CloudflaredSettings, config_path: &Path) -> Vec<OsString> {
        let mut args: Vec<OsString> = vec![
            "tunnel".into(),
            "--config".into(),
            config_path.as_os_str().to_os_string(),
            "--no-autoupdate".into(),
            "--loglevel".into(),
            settings.log_level.clone().into(),
        ];
        if settings.protocol != "auto" {
            args.push("--protocol".into());
            args.push(settings.protocol.clone().into());
        }
        if settings.edge_ip_version != "auto" {
            args.push("--edge-ip-version".into());
            args.push(settings.edge_ip_version.clone().into());
        }
        args.push("run".into());
        args
    }

    /// cloudflared logs as `<time> <LVL> <message>`, e.g.
    /// `2025-01-01T00:00:00Z INF Registered tunnel connection connIndex=0 ...`.
    fn classify(line: &str) -> LogSignal {
        if line.contains(" ERR ") || line.contains(" FTL ") {
            LogSignal::Error
        } else if line.contains("Registered tunnel connection") {
            LogSignal::Connected
        } else {
            LogSignal::None
        }
    }
}

impl TunnelProvider for CloudflaredProvider {
    fn prepare(&self, ctx: &TunnelContext) -> Result<LaunchSpec, (String, String)> {
        let settings = {
            let conn = ctx.db.conn();
            CloudflaredRepository::get(&conn, &ctx.tunnel.id)
                .map_err(|e| ("B1000".to_string(), e.to_string()))?
                .unwrap_or_else(|| CloudflaredSettings::new(&ctx.tunnel.id))
        };

        if settings.token.is_empty() {
            return Err((
                "B1001".to_string(),
                "未配置 Cloudflare Tunnel 令牌".to_string(),
            ));
        }
        if let Err(field) = CloudflaredRepository::validate(&settings) {
            return Err(("B1000".to_string(), format!("Invalid {}", field)));
        }

        let binary = Self::resolve_binary(ctx, &settings)?;

        if let Some(dir) = ctx.config_path.parent() {
            let _ = fs::create_dir_all(dir);
        }
        if let Some(dir) = ctx.log_path.parent() {
            let _ = fs::create_dir_all(dir);
        }
        if let Err(e) = fs::write(ctx.config_path, ISOLATED_CONFIG) {
            return Err(("B1000".to_string(), format!("写入配置文件失败: {}", e)));
        }

        Ok(LaunchSpec {
            binary,
            args: Self::build_args(&settings, ctx.config_path),
            envs: vec![("TUNNEL_TOKEN".to_string(), settings.token)],
            log_path: ctx.log_path.to_path_buf(),
        })
    }

    fn log_classifier(&self) -> LogClassifier {
        Self::classify
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn args_never_contain_the_token() {
        let mut settings = CloudflaredSettings::new("t");
        settings.token = "eyJhIjoiYWNjb3VudCIsInQiOiJ0dW5uZWwiLCJzIjoic2VjcmV0In0=".to_string();
        settings.protocol = "http2".to_string();
        settings.edge_ip_version = "4".to_string();
        let args: Vec<String> = CloudflaredProvider::build_args(&settings, Path::new("c.yml"))
            .into_iter()
            .map(|a| a.to_string_lossy().to_string())
            .collect();
        assert_eq!(
            args,
            [
                "tunnel",
                "--config",
                "c.yml",
                "--no-autoupdate",
                "--loglevel",
                "info",
                "--protocol",
                "http2",
                "--edge-ip-version",
                "4",
                "run"
            ]
        );
        assert!(!args.iter().any(|a| a.contains(&settings.token)));

        let defaults: Vec<String> =
            CloudflaredProvider::build_args(&CloudflaredSettings::new("t"), Path::new("c.yml"))
                .into_iter()
                .map(|a| a.to_string_lossy().to_string())
                .collect();
        assert_eq!(
            defaults,
            [
                "tunnel",
                "--config",
                "c.yml",
                "--no-autoupdate",
                "--loglevel",
                "info",
                "run"
            ]
        );
    }

    #[test]
    fn classifies_cloudflared_log_lines() {
        assert!(matches!(
            CloudflaredProvider::classify(
                "2025-01-01T00:00:00Z INF Registered tunnel connection connIndex=0 location=sjc01"
            ),
            LogSignal::Connected
        ));
        assert!(matches!(
            CloudflaredProvider::classify(
                "2025-01-01T00:00:00Z ERR Register tunnel error from server side error=\"Unauthorized\""
            ),
            LogSignal::Error
        ));
        assert!(matches!(
            CloudflaredProvider::classify("2025-01-01T00:00:00Z INF Starting tunnel tunnelID=abc"),
            LogSignal::None
        ));
    }
}
